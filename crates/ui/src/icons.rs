#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;

    /// Every hand-written `char` constant above must match the generated JSON mapping exactly
    /// — this is what catches a `make icon-font` rerun reassigning a codepoint (it shouldn't,
    /// per the script's stability guarantee, but this is the cheap check that it didn't) out
    /// from under a constant nobody remembered to update.
    #[test]
    fn constants_match_generated_mapping() {
        let mapping: BTreeMap<String, u32> =
            serde_json::from_str(CODEPOINTS_JSON).expect("lucide-oca.json should be valid JSON");

        let constants: BTreeMap<&str, char> = BTreeMap::from([
            ("camera", CAMERA),
            ("chevron-down", CHEVRON_DOWN),
            ("chevron-left", CHEVRON_LEFT),
            ("chevron-right", CHEVRON_RIGHT),
            ("ellipsis-vertical", ELLIPSIS_VERTICAL),
            ("eye", EYE),
            ("eye-off", EYE_OFF),
            ("fast-forward", FAST_FORWARD),
            ("fold-horizontal", FOLD_HORIZONTAL),
            ("hand", HAND),
            ("lock", LOCK),
            ("lock-open", LOCK_OPEN),
            ("mouse-pointer-2", MOUSE_POINTER_2),
            ("music", MUSIC),
            ("pause", PAUSE),
            ("play", PLAY),
            ("repeat", REPEAT),
            ("rewind", REWIND),
            ("scissors", SCISSORS),
            ("settings", SETTINGS),
            ("skip-back", SKIP_BACK),
            ("skip-forward", SKIP_FORWARD),
            ("type", TYPE),
            ("upload", UPLOAD),
            ("wand-sparkles", WAND_SPARKLES),
        ]);

        assert_eq!(
            mapping.len(),
            constants.len(),
            "lucide-oca.json and this module's constants list a different number of icons — \
             one was updated without the other"
        );
        for (name, codepoint) in &mapping {
            let expected = char::from_u32(*codepoint).expect("codepoint should be valid char");
            let actual = constants.get(name.as_str()).unwrap_or_else(|| {
                panic!("lucide-oca.json has icon `{name}` with no matching constant in icons.rs")
            });
            assert_eq!(
                *actual, expected,
                "icons::{name} constant doesn't match lucide-oca.json's codepoint for `{name}`"
            );
        }
    }
}
