//! The Lucide icon font — route (b) from `spec/architecture/editor-ui-visual-redesign.md`'s
//! "Icon set" section: Private-Use-Area codepoints in a dedicated [`egui::FontFamily`],
//! rendered exactly like every existing single-glyph icon in this codebase already is (via
//! `RichText`/`painter.text`), not a separate SVG-to-texture pipeline.
//!
//! `assets/fonts/lucide-oca.ttf` and its name→codepoint mapping (`lucide-oca.json`) are
//! generated by `tools/icon-font/build-icon-font.ts` from the vendored SVGs in
//! `spec/architecture/assets/icons/` — see that script's own doc comment to regenerate after
//! adding/removing an icon (`make icon-font`). The `char` constants below are hand-written for
//! ergonomic call sites (`icons::LOCK` beats a string lookup at every use site); [`tests`]
//! checks them against the embedded JSON mapping so a regenerated font with different
//! codepoints fails a test instead of silently drawing the wrong glyph.
//!
//! `#![allow(dead_code)]`: most constants (and, outside `cfg(test)`, the embedded JSON string)
//! have no call site yet — wiring individual screens over from their current emoji/text glyphs
//! is a separate, per-screen slice of work (see the redesign doc's Icon set section). `ui` is a
//! bin crate, so nothing external proves these `pub` items reachable the way a lib crate's
//! would be; this is a deliberately-ahead-of-its-call-sites public API surface, not actually-
//! dead code.
#![allow(dead_code)]

use egui::{FontData, FontDefinitions, FontFamily};
use std::sync::Arc;

/// The dedicated font family name every icon call site renders through, e.g.
/// `RichText::new(icons::LOCK).family(icons::family())`.
pub fn family() -> FontFamily {
    FontFamily::Name("lucide-oca".into())
}

const FONT_BYTES: &[u8] = include_bytes!("../assets/fonts/lucide-oca.ttf");
const CODEPOINTS_JSON: &str = include_str!("../assets/fonts/lucide-oca.json");

/// Registers the icon font with egui. Call once at startup, alongside [`crate::theme::apply`].
pub fn install(ctx: &egui::Context) {
    let mut fonts = FontDefinitions::default();
    fonts.font_data.insert(
        "lucide-oca".to_owned(),
        Arc::new(FontData::from_static(FONT_BYTES)),
    );
    fonts
        .families
        .insert(family(), vec!["lucide-oca".to_owned()]);
    ctx.set_fonts(fonts);
}

// One `char` per vendored icon (`spec/architecture/assets/icons/*.svg`), matching
// `assets/fonts/lucide-oca.json`'s name→codepoint mapping.
